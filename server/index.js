import "dotenv/config";
import express from "express";
import multer from "multer";
import { CONFIG, generateContent, probe, GemmaError } from "./gemma.js";
import { buildAnalyzePrompt, CATEGORIES } from "./prompts.js";
import { extractJson, normalizeAnalysis, composeTicket } from "./schema.js";
import { DEMO_ANALYSIS } from "./demo.js";

const app = express();
app.use(express.json({ limit: "1mb" }));
app.use(express.urlencoded({ extended: true, limit: "1mb" }));

const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: 6 * 1024 * 1024, files: 1 },
  fileFilter: (_req, file, cb) => {
    const ok = ["image/jpeg", "image/png", "image/webp"].includes(file.mimetype);
    cb(ok ? null : new Error("Only JPEG, PNG or WebP images up to 6 MB are accepted."), ok);
  },
});

const sendError = (res, err) => {
  const isGemma = err instanceof GemmaError;
  const status = isGemma
    ? err.kind === "not_configured"
      ? 503
      : err.kind === "timeout" || err.kind === "network"
        ? 504
        : 502
    : 400;
  console.error(`[error] ${err.message}${err.detail ? ` :: ${err.detail}` : ""}`);
  res.status(status).json({
    error: err.message,
    kind: isGemma ? err.kind : "bad_input",
    detail: isGemma && err.detail ? String(err.detail).slice(0, 400) : undefined,
  });
};

app.get("/api/health", async (_req, res) => {
  const health = await probe();
  res.json({
    ...health,
    categories: CATEGORIES,
    privacy:
      "Your description and photo are sent to the configured model provider for analysis and are not stored by this application.",
  });
});

app.post("/api/analyze", upload.single("image"), async (req, res) => {
  try {
    const description = String(req.body.description || "").trim();
    const location = String(req.body.location || "").trim();
    const category = String(req.body.category || "").trim();
    const context = String(req.body.context || "").trim();

    if (!description) {
      return res.status(400).json({
        error: "Please describe the problem before analysing.",
        kind: "bad_input",
      });
    }
    if (description.length > 2000) {
      return res.status(400).json({
        error: "Description is too long (2000 characters maximum).",
        kind: "bad_input",
      });
    }
    const input = { description, location, category, context };

    if (CONFIG.demoMode) {
      console.log("[demo] returning SAMPLE analysis - no model call made");
      return res.json({
        sample: true,
        source: "DEMO_MODE sample data - NOT generated by the model",
        input,
        analysis: normalizeAnalysis(DEMO_ANALYSIS, input),
      });
    }

    const imagePart = req.file
      ? {
          inline_data: {
            mime_type: req.file.mimetype,
            data: req.file.buffer.toString("base64"),
          },
        }
      : null;

    const parts = imagePart
      ? [imagePart, { text: buildAnalyzePrompt({ ...input, hasImage: true }) }]
      : [{ text: buildAnalyzePrompt({ ...input, hasImage: false }) }];

    const t0 = Date.now();
    const text = await generateContent([{ role: "user", parts }]);
    let analysis;
    try {
      analysis = normalizeAnalysis(extractJson(text), input);
    } catch (firstErr) {
      // One corrective retry: ask again for bare JSON.
      console.warn(`[analyze] JSON repair failed, retrying once: ${firstErr.message}`);
      const retryText = await generateContent([
        {
          role: "user",
          parts: [
            { text: buildAnalyzePrompt({ ...input, hasImage: !!imagePart }) },
            { text: "Your previous reply was not parseable JSON. Reply with ONLY the JSON object." },
          ],
        },
      ]);
      analysis = normalizeAnalysis(extractJson(retryText), input);
    }

    res.json({
      sample: false,
      model: CONFIG.model,
      latency_ms: Date.now() - t0,
      input,
      analysis,
    });
  } catch (err) {
    sendError(res, err);
  }
});

// Ticket generation is deterministic - validated analysis + user answers.
app.post("/api/ticket", (req, res) => {
  try {
    const { analysis, input, answers } = req.body || {};
    if (!analysis || !input) {
      return res.status(400).json({
        error: "Missing analysis or original input for ticket generation.",
        kind: "bad_input",
      });
    }
    const ticket = composeTicket({
      analysis: normalizeAnalysis(analysis, input),
      input: {
        description: String(input.description || ""),
        location: String(input.location || ""),
        category: String(input.category || ""),
        context: String(input.context || ""),
      },
      answers: Array.isArray(answers) ? answers : [],
    });
    res.json({ ticket });
  } catch (err) {
    sendError(res, err);
  }
});

// Multer and body-parser errors
app.use((err, _req, res, _next) => {
  if (err?.code === "LIMIT_FILE_SIZE") {
    return res.status(400).json({
      error: "Image is larger than 6 MB. Please use a smaller photo.",
      kind: "bad_input",
    });
  }
  sendError(res, err instanceof Error ? err : new Error(String(err)));
});

const port = Number(process.env.PORT || 8787);
app.listen(port, () => {
  console.log(`Proof-of-Place API on http://localhost:${port}`);
  console.log(`  model:  ${CONFIG.model}`);
  console.log(`  key:    ${CONFIG.apiKey ? "configured (hidden)" : "NOT SET"}`);
  console.log(`  mode:   ${CONFIG.demoMode ? "DEMO (sample data, no model calls)" : "live"}`);
});
